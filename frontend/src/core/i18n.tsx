const arabicToEnglish = new Map(Object.entries(arabic).map(([english, translated]) => [translated.toLocaleLowerCase('ar'), english]));

export function translateText(value: string, locale: Locale): string {
  if (locale === 'en') return value;
  const trimmed = value.trim();
  if (arabic[trimmed]) return preserveSpacing(value, arabic[trimmed]);
  const posted = trimmed.match(/^Posted (\d+) days? ago$/i);
  if (posted) return preserveSpacing(value, `نُشرت ${new Intl.RelativeTimeFormat('ar-EG', { numeric: 'auto' }).format(-Number(posted[1]), 'day')}`);
  const week = trimmed.match(/^Posted (\d+) weeks? ago$/i);
  if (week) return preserveSpacing(value, `نُشرت ${new Intl.RelativeTimeFormat('ar-EG', { numeric: 'auto' }).format(-Number(week[1]), 'week')}`);
  const relativeDays = trimmed.match(/^(\d+) days? ago$/i);
  if (relativeDays) return preserveSpacing(value, new Intl.RelativeTimeFormat('ar-EG', { numeric: 'auto' }).format(-Number(relativeDays[1]), 'day'));
  const relativeWeeks = trimmed.match(/^(\d+) weeks? ago$/i);
  if (relativeWeeks) return preserveSpacing(value, new Intl.RelativeTimeFormat('ar-EG', { numeric: 'auto' }).format(-Number(relativeWeeks[1]), 'week'));
  const chars = trimmed.match(/^(\d+) chars?$/i);
  if (chars) return preserveSpacing(value, `${new Intl.NumberFormat('ar-EG').format(Number(chars[1]))} حرف`);
  const salary = trimmed.match(/^([A-Z]{3}) ([\d,.]+)(k)?–([\d,.]+)(k)? \/ month$/);
  if (salary) {
    const number = (raw: string, thousands: string | undefined) => Number(raw.replaceAll(',', '')) * (thousands ? 1000 : 1);
    const format = new Intl.NumberFormat('ar-EG', { style: 'currency', currency: salary[1], maximumFractionDigits: 0 });
    return preserveSpacing(value, `${format.format(number(salary[2], salary[3]))} – ${format.format(number(salary[4], salary[5]))} / شهر`);
  }
  return value;
}

function preserveSpacing(original: string, translated: string) {
  const leading = original.match(/^\s*/)?.[0] ?? '';
  const trailing = original.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

